/**
 * Links the app to a Google Sheet without any Google API or browser: a small Apps Script project is attached
 * to the workbook and deployed as a web app with clasp. The app then reads the workbook through that address.
 *
 * Once per machine, from the repository root:
 *   1. npm install -g @google/clasp                 (Node.js required)
 *   2. Turn on "Google Apps Script API" at https://script.google.com/home/usersettings
 *   3. clasp login                                   (company Google account, in the browser)
 *   4. node gsheet/install.mjs <sheet link or id>    (a NATIVE Google Sheet: for an .xlsx stored in Drive,
 *                                                     use File > Save as Google Sheets first)
 *      writes gsheet/config.json, then opens the web app page: authorise the script with the same account.
 *
 * Running it again after a change in gsheet/src/ updates the script (same address, same token).
 * gsheet/config.json, gsheet/.clasp.json and gsheet/build/ belong to the machine: not committed.
 * Access is limited to the accounts of the company ("DOMAIN") and protected by the random token as well.
 */
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const sources = path.join(here, 'src');
const build = path.join(here, 'build');
const configPath = path.join(here, 'config.json');
const claspProject = path.join(here, '.clasp.json');
const TITLE = 'PLM Automation - Reader';
const DESCRIPTION = 'PLM Automation';
const DEPLOYMENT = /AKfyc[\w-]{20,}/;

const die = (message) => { console.error(message); process.exit(1); };

/** Runs clasp in gsheet/ and stops the installation if it fails. Returns the output text. */
function clasp(...args) {
  const r = spawnSync('clasp', args, { cwd: here, encoding: 'utf8', shell: process.platform === 'win32' });
  const text = [r.stdout, r.stderr].filter((t) => t && t.trim()).map((t) => t.trim()).join('\n');
  if (r.error || r.status) {
    die(`"clasp ${args.join(' ')}" failed:\n${text || r.error}\n\nCheck: npm install -g @google/clasp, clasp login, and the Apps Script API turned on at https://script.google.com/home/usersettings`);
  }
  return text;
}

let config = {};
try { config = JSON.parse(fs.readFileSync(configPath, 'utf8').replace(/^﻿/, '')); } catch { /* first install */ }
const token = config.token || randomBytes(32).toString('base64url');

if (!fs.existsSync(claspProject)) {
  const wanted = process.argv[2] || '';
  const sheetId = wanted.match(/\/d\/([\w-]{10,})/)?.[1] || (/^[\w-]{20,}$/.test(wanted) ? wanted : '');
  if (!sheetId) die('Give the Google Sheet link or id: node gsheet/install.mjs https://docs.google.com/spreadsheets/d/<id>/edit');
  console.log('Creating the script and attaching it to the sheet...');
  fs.mkdirSync(build, { recursive: true });
  clasp('create-script', '--parentId', sheetId, '--title', TITLE, '--rootDir', 'build');
}

// What is sent: the sources of the repository, plus the token (Secret.js, never committed).
fs.rmSync(build, { recursive: true, force: true });
fs.cpSync(sources, build, { recursive: true });
fs.writeFileSync(path.join(build, 'Secret.js'), `// Generated by gsheet/install.mjs: do not commit.\nconst JETON = "${token}";\n`);
console.log('Sending the script...');
clasp('push', '--force');

console.log('Deploying the web app...');
let existing = config.deployment || '';
if (!existing) {
  const listed = clasp('list-deployments').split(/\r?\n/).filter((l) => l.includes(DESCRIPTION) && !l.includes('@HEAD') && DEPLOYMENT.test(l));
  existing = listed.length ? listed[listed.length - 1].match(DEPLOYMENT)[0] : '';
}
const out = clasp('create-deployment', '--description', DESCRIPTION, ...(existing ? ['--deploymentId', existing] : []));
const deployment = out.match(DEPLOYMENT)?.[0] || existing;
if (!deployment) die(`Deployment id not found in the answer of clasp:\n${out || '(empty answer)'}`);

const url = `https://script.google.com/macros/s/${deployment}/exec`;
fs.writeFileSync(configPath, JSON.stringify({ url, token, deployment }, null, 1));
console.log(`\nReady. Web app: ${url}`);
console.log('Open that address in your browser once and authorise the script (same Google account), then start the app.');
